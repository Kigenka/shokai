// Copies the reference implementation's protocol core (reference/engawa/src)
// into src/core, byte for byte under a one-line header, so the SDK and the reference that passes every suite never drift.
//   node scripts/sync-core.mjs          copy
//   node scripts/sync-core.mjs --check  exit 1 if src/core differs from the reference (CI)
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const candidates = [join(here, "../../../reference/engawa/src")];
const SRC = candidates.find((d) => existsSync(join(d, "host.ts")));
if (!SRC) { console.error("sync-core: reference source not found (looked in " + candidates.join(", ") + ")"); process.exit(2); }
const DST = join(here, "../src/core");
const MODULES = ["crypto", "verify", "trust", "gate", "policy", "shapes", "host", "inbound", "place", "door", "version", "i18n"];
const HEADER = "// SPDX-License-Identifier: Apache-2.0\n// SPDX-FileCopyrightText: 2026 Yu Sung Yeh\n// GENERATED by scripts/sync-core.mjs from the Shōkai reference implementation. Do not edit; edit the reference and re-sync.\n";
// The SDK accepts no legacy (pre-0.3) cards: its compat module carries no legacy identifier at all.
const COMPAT = HEADER + "/** The SDK accepts no pre-0.3 cards; this value never equals a card's protocol. */\nexport const LEGACY_PROTOCOL = \"\\u0000none\";\n";
const want = Object.fromEntries(MODULES.map((m) => [m + ".ts", HEADER + readFileSync(join(SRC, m + ".ts"), "utf8")]));
want["compat.ts"] = COMPAT;
// `@kigenka/shokai/core`: one entry point for the whole core (protocol types, verification, the gate, policy, the host, the door).
want["index.ts"] = HEADER + "// The protocol core, synced from the reference implementation: import it as @kigenka/shokai/core.\n"
  + MODULES.map((m) => m === "shapes" ? `export type * from "./shapes.js";` : `export * from "./${m}.js";`).join("\n") + "\n";
const check = process.argv.includes("--check"); let drift = 0;
for (const [f, body] of Object.entries(want)) {
  const p = join(DST, f); const have = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (have === body) continue;
  if (check) { console.error("drift: src/core/" + f); drift++; } else writeFileSync(p, body);
}
// the normative test vectors travel with the runner
const tvSrc = [join(here, "../../../conformance/test-vectors.json")].find(existsSync);
if (tvSrc) { const p = join(here, "../conformance-data/test-vectors.json"); const body = readFileSync(tvSrc, "utf8"); const have = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (have !== body) { if (check) { console.error("drift: conformance-data/test-vectors.json"); drift++; } else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body); } } }
// The normative text travels with the package (spec/), so every "§7.2", "C174" or "Appendix A.1" in the SDK, its errors and the
// runner's output resolves for a reader who has only the package: SPEC.md, the types, the conformance checklist and data,
// the extensions, the threat model, and the documents SPEC.md links to.
const ROOT = join(here, "../../..");
const pick = (rel, alts = []) => [rel, ...alts].map((r) => join(ROOT, r)).find(existsSync);
const SPEC_FILES = { "SPEC.md": pick("SPEC.md"), "protocol-shapes.ts": pick("protocol-shapes.ts"), "THREAT-MODEL.md": pick("THREAT-MODEL.md"),
  "CHANGELOG.md": pick("repo-export/public/CHANGELOG.md", ["CHANGELOG.md"]), "PATENTS.md": pick("repo-export/public/PATENTS.md", ["PATENTS.md"]),
  "TRADEMARKS.md": pick("repo-export/public/TRADEMARKS.md", ["TRADEMARKS.md"]), "LICENSE": pick("repo-export/public/LICENSE", ["LICENSE"]),
  "conformance/golden-traces.md": pick("conformance/golden-traces.md"), "conformance/homes.json": pick("conformance/homes.json"),
  "conformance/test-vectors.json": pick("conformance/test-vectors.json"),
  "SIGNING.md": pick("SIGNING.md"), "DECISIONS.md": pick("DECISIONS.md"), "docs/relationship-to-other-protocols.md": pick("docs/relationship-to-other-protocols.md"),
  "proposals/P18-owner-key-continuity.md": pick("proposals/P18-owner-key-continuity.md"), "proposals/P23-identity-binding.md": pick("proposals/P23-identity-binding.md"), "proposals/P24-owner-key-move.md": pick("proposals/P24-owner-key-move.md"), "QUICKSTART.md": pick("QUICKSTART.md") };
const extDir = join(ROOT, "extensions");
if (existsSync(extDir)) for (const f of readdirSync(extDir).filter((f) => f.endsWith(".md"))) SPEC_FILES["extensions/" + f] = join(extDir, f);
for (const [rel, srcPath] of Object.entries(SPEC_FILES)) {
  if (!srcPath) { console.error("sync-core: spec file not found: " + rel); drift++; continue; }
  const p = join(here, "../spec", rel); const body = readFileSync(srcPath, "utf8"); const have = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (have === body) continue;
  if (check) { console.error("drift: spec/" + rel); drift++; } else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body); }
}
if (check) { if (drift) process.exit(1); console.log(`sync-core: src/core matches the reference (${Object.keys(want).length} modules)`); }
else console.log(`sync-core: ${Object.keys(want).length} modules written to src/core from ${SRC}; spec/ refreshed`);
