const readHouse = (io: Io, path = "shokai/house.json"): { house: any; path: string } => {
  const p = join(io.cwd, path); if (!existsSync(p)) throw new Error(`${path} not found: write it with \`shokai house new\` (by hand) or in the setup conversation (agent)`);
  return { house: JSON.parse(readFileSync(p, "utf8")), path };
};
const write = (io: Io, rel: string, body: string, written: string[], mode?: number) => {
  const p = join(io.cwd, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body, mode ? { mode } : {}); if (mode) chmodSync(p, mode); written.push(rel);
};

/** The door's DoorPointer, from house.json alone (no keys): what a site serves as /.well-known/shokai. */
export function wellKnownFor(h: House): string {
  const d = createDoor(houseToDoorOptions(h, { approvedBy: { name: "preview", role: "preview" } }));
  return JSON.stringify(d.wellKnown(), null, 2) + "\n";
}

const DOOR_MODULE = `// Generated by \`shokai init\` from shokai/house.json. Change house.json, not this file, then run \`shokai house check\`;
// a changed house needs a new Shōkai host card signed by the owner (\`shokai host-card request\`).
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createDoor, houseToDoorOptions, importRepresentativeKey, fileStore } from "@kigenka/shokai";

const root = process.env.SHOKAI_ROOT ?? process.cwd();
let door;
/**
 * The door, opened on first use. Throws (code SHOKAI_NO_HOST_CARD) until the owner has signed the Shōkai host card:
 * no Shōkai host card, no admission (SPEC §2.3).
 */
export function getDoor() {
  if (door) return door;
  const house = JSON.parse(readFileSync(join(root, "shokai/house.json"), "utf8"));
  const cardFile = join(root, "shokai/host-card.json");
  if (!existsSync(cardFile)) throw Object.assign(new Error("shokai/host-card.json is missing: the owner signs the Shōkai host card first (shokai host-card request)"), { code: "SHOKAI_NO_HOST_CARD" });
  // The door's own key: SHOKAI_REP_KEY in the environment (hosted), or .shokai/rep.key (never committed).
  const rep = importRepresentativeKey(process.env.SHOKAI_REP_KEY ?? readFileSync(join(root, ".shokai/rep.key"), "utf8"));
  // Durable state (SPEC §3.6) and visits in progress. Several processes on this machine may share this file; on a serverless host
  // or across machines, use kvStore({ get, set, cas }) with your key-value service, so any instance can answer any message.
  const store = fileStore(join(root, ".shokai/state.json"));
  door = createDoor(houseToDoorOptions(house, { card: JSON.parse(readFileSync(cardFile, "utf8")), keys: { rep }, store }));
  return door;
}
`;
