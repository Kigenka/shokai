/** The project's stack, from package.json (and tsconfig.json, app/). Static when there is no package.json. */
export function detect(cwd: string): { framework: Framework; typescript: boolean; app_dir?: string; module: "esm" | "cjs"; reasons: string[] } {
  const reasons: string[] = []; const p = join(cwd, "package.json");
  const typescript = existsSync(join(cwd, "tsconfig.json"));
  if (!existsSync(p)) { reasons.push("no package.json: a static site (the door is hosted elsewhere; the site points to it)"); return { framework: "static", typescript, module: "esm", reasons }; }
  const pkg = JSON.parse(readFileSync(p, "utf8")); const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const module = pkg.type === "module" ? "esm" : "cjs";
  const app_dir = ["app", "src/app"].find((d) => existsSync(join(cwd, d)));
  let framework: Framework = "node";
  if (deps.next) { framework = "next"; reasons.push(`next ${deps.next} in package.json${app_dir ? `, App Router at ${app_dir}/` : ""}`); }
  else if (deps.hono) { framework = "hono"; reasons.push(`hono ${deps.hono} in package.json`); }
  else if (deps.express) { framework = "express"; reasons.push(`express ${deps.express} in package.json`); }
  else reasons.push("package.json without next, hono or express: a plain Node server (node:http)");
  return { framework, typescript, ...(app_dir ? { app_dir } : {}), module, reasons };
}

