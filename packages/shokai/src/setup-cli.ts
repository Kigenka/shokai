const NEXT_ROUTE = (doorImport: string) => `// Generated by \`shokai init\`: the door's routes in a Next.js app (App Router). /.well-known/shokai is served from public/.
import { nextDoor } from "@kigenka/shokai";
import { getDoor } from "${doorImport}";
export const runtime = "nodejs";
export const dynamic = "force-dynamic";
const closed = () => new Response(JSON.stringify({ protocol: "shokai/0.5", messages: [] }), { status: 503, headers: { "content-type": "application/json", "retry-after": "86400" } });
const handle = (method) => async (req) => { let d; try { d = getDoor(); } catch { return closed(); } return nextDoor(d)[method](req); };
export const GET = handle("GET");
export const POST = handle("POST");
export const HEAD = handle("HEAD");
`;

/** `shokai init`: the door's files for this stack, from shokai/house.json. Returns the files written. */
export function init(io: Io, o: { framework?: Framework; house?: string } = {}): { written: string[]; next_steps: string[] } {
  const { house } = readHouse(io, o.house); const problems = checkHouse(house);
  if (problems.length) throw new Error("house.json isn't ready (run `shokai house check`):\n  " + problems.map((p) => `${p.path}: ${p.message}`).join("\n  "));
  const fw = o.framework ?? detect(io.cwd).framework; if (!FRAMEWORKS.includes(fw)) throw new Error(`--framework: one of ${FRAMEWORKS.join(", ")}`);
  const written: string[] = []; const steps: string[] = [];
  const wk = wellKnownFor(house);
  if (fw === "static") {
    write(io, "public/.well-known/shokai", wk, written);
    steps.push(`Publish public/.well-known/shokai with your site, and add to your pages' <head>: <link rel="shokai" href="/.well-known/shokai">`,
      `Your door itself runs where ${house.door.base_url} points (a host or platform that runs it).`);
    return { written, next_steps: steps };
  }
  // the door's own key: made once, kept out of git, never printed
  const keyFile = join(io.cwd, ".shokai/rep.key");
  if (!existsSync(keyFile) && !io.env.SHOKAI_REP_KEY) { mkdirSync(dirname(keyFile), { recursive: true, mode: 0o700 }); writeFileSync(keyFile, exportRepresentativeKey(generateRepresentativeKey()) + "\n", { mode: 0o600 }); chmodSync(keyFile, 0o600); written.push(".shokai/rep.key (private, mode 600)"); }
  const gi = join(io.cwd, ".gitignore"); const giText = existsSync(gi) ? readFileSync(gi, "utf8") : "";
  if (!/^\/?\.shokai\/?$/m.test(giText)) { appendFileSync(gi, (giText && !giText.endsWith("\n") ? "\n" : "") + ".shokai/\n"); written.push(".gitignore (+ .shokai/)"); }
  write(io, "shokai/door.mjs", DOOR_MODULE, written);
  if (fw === "next") {
    const appDir = detect(io.cwd).app_dir ?? "app"; const routeDir = `${appDir}/shokai/[[...path]]`;
    const doorImport = relative(join(io.cwd, routeDir), join(io.cwd, "shokai/door.mjs")).split("\\").join("/");
    write(io, `${routeDir}/route.js`, NEXT_ROUTE(doorImport.startsWith(".") ? doorImport : "./" + doorImport), written);
    write(io, "public/.well-known/shokai", wk, written);
    steps.push(`Nothing to add to your code: ${routeDir}/route.js answers the door's addresses, public/.well-known/shokai lets agents find it.`);
  } else {
    const g = GLUE[fw]; write(io, g.file, g.body, written); steps.push(`Add one line to your server: ${g.line}`);
  }
  steps.push("Prepare the Shōkai host card for the owner to sign: shokai host-card request");
  return { written, next_steps: steps };
}

export async function setup(argv: string[], io: Io): Promise<number> {
  const [cmd, sub] = argv; const flag = (n: string) => { const i = argv.indexOf("--" + n); return i >= 0 ? argv[i + 1] : undefined; };
  const json = argv.includes("--json");
  try {
    if (cmd === "detect") { const d = detect(io.cwd); io.out(json ? JSON.stringify(d) : `${d.framework}${d.typescript ? " (TypeScript)" : ""}: ${d.reasons.join("; ")}`); return 0; }
    if (cmd === "house" && sub === "new") {
      const p = join(io.cwd, "shokai/house.json"); if (existsSync(p)) { io.err("shokai/house.json already exists; edit it"); return 1; }
      const w: string[] = []; write(io, "shokai/house.json", JSON.stringify(HOUSE_TEMPLATE, null, 2) + "\n", w);
      io.out("Wrote shokai/house.json. Fill in every <…>, then: shokai house check"); return 0;
    }
    if (cmd === "house" && sub === "check") {
      const { house, path } = readHouse(io, flag("house") ?? (argv[2]?.startsWith("--") ? undefined : argv[2])); const p = checkHouse(house);
      if (json) io.out(JSON.stringify({ ok: !p.length, problems: p }));
      else if (!p.length) io.out(`${path}: ready. Next: shokai house preview`);
      else io.out(`${path}: ${p.length} thing${p.length > 1 ? "s" : ""} to fix\n` + p.map((x) => `  ${x.path}: ${x.message}`).join("\n"));
      return p.length ? 1 : 0;
    }
    if (cmd === "house" && sub === "preview") { const { house } = readHouse(io, flag("house")); io.out(previewHouse(house)); return 0; }
    if (cmd === "init") {
      const r = init(io, { framework: flag("framework") as Framework | undefined, house: flag("house") });
      io.out(json ? JSON.stringify(r) : "Wrote:\n" + r.written.map((x) => "  " + x).join("\n") + "\nNext:\n" + r.next_steps.map((x) => "  " + x).join("\n")); return 0;
    }
    if (cmd === "host-card" && sub === "request") {
      const { house } = readHouse(io, flag("house"));
      const rep = importRepresentativeKey(io.env.SHOKAI_REP_KEY ?? readFileSync(join(io.cwd, ".shokai/rep.key"), "utf8"));
      const req = hostCardRequest(house, representativePublic(rep)); const w: string[] = [];
      write(io, "shokai/host-card.request.json", JSON.stringify(req, null, 2) + "\n", w);
      io.out(json ? JSON.stringify({ written: w, item: "host-card" }) : [
        "Wrote shokai/host-card.request.json: the Shōkai host card, ready for the owner to sign.",
        "The owner signs it with their own passkey on the signing page (only the owner can):",
        "  ITEMS=shokai/host-card.request.json RP_ID=<your signing hostname> TOKEN=<a long random secret> node reference/signing-page/server.mjs",
        "  (the reference signing page in the Shōkai source; see its README for the https front a phone needs)",
        "The page shows the house rules and the whole leaflet before the passkey. Then copy DATA_DIR/signed/host-card.json to shokai/host-card.json",
        "and run: shokai host-card verify"].join("\n"));
      return 0;
    }
    if (cmd === "host-card" && sub === "verify") {
      const { house } = readHouse(io, flag("house")); const file = join(io.cwd, flag("card") ?? "shokai/host-card.json");
      const rep = importRepresentativeKey(io.env.SHOKAI_REP_KEY ?? readFileSync(join(io.cwd, ".shokai/rep.key"), "utf8"));
      const card = fromSigningPage(JSON.parse(readFileSync(file, "utf8")));
      try { const d = createDoor(houseToDoorOptions(house, { card: card as any, keys: { rep } }));
        io.out(json ? JSON.stringify({ ok: true, house_digest: d.listing().places[0]?.house_digest }) : `The Shōkai host card fits this house and key: the door can open (house digest ${d.listing().places[0]?.house_digest}).`); return 0;
      } catch (e: any) { io.out(json ? JSON.stringify({ ok: false, code: e.code, why: e.message }) : `The Shōkai host card doesn't fit: ${e.message}`); return 1; }
    }
    if (cmd === "agent-guide") { io.out(readFileSync(argv.includes("--manifest") ? INSTALL_MANIFEST : AGENT_GUIDE, "utf8")); return 0; }
  } catch (e: any) { io.err(String(e?.message ?? e)); return 1; }
  io.err(SETUP_USAGE); return 1;
}
