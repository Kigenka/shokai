// Builds site/: sign.kigenka.com in SERVERLESS mode (Vercel Functions plus a store; no tunnel, no machine on during a session).
//   /, /about, /style.css, /robots.txt   static, the same inert page and notice as deploy/sign-front
//   /p/<token>/*                          api/p.js: the rc4 reference signing page (src/core.mjs), state in the store
//   /api/admin                            api/admin.js: steward only (SIGN_ADMIN_SECRET): load the public owner credential,
//                                         open a session (one-time token, at most 30 minutes), read results, close it
// The page logic (describe.mjs, items.mjs, webauthn.mjs) and the page files are copied from reference/signing-page, unchanged.
// Usage: node deploy/sign-serverless/build.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const HERE = dirname(fileURLToPath(import.meta.url)), REF = join(HERE, "..", "..", "reference", "signing-page"), FRONT = join(HERE, "..", "sign-front", "site"), OUT = join(HERE, "site");
const CONFIG = { rpId: "sign.kigenka.com", notice: "test-stage", noticeDays: 90 };
const LIC = "// SPDX-License-Identifier: Apache-2.0\n// SPDX-FileCopyrightText: 2026 Yu Sung Yeh\n";
const pages = Object.fromEntries([["index", "index.html"], ["app", "app.js"], ["style", "style.css"], ["about", "about.html"]].map(([k, f]) => [k, readFileSync(join(REF, "public", f), "utf8")]));
const front = JSON.parse(readFileSync(join(FRONT, "vercel.json"), "utf8"));
const handler = (fn) => `${LIC}// Generated by deploy/sign-serverless/build.mjs. ${fn === "page" ? "/p/<token>/* (rewritten here as ?p=<token>/<sub>)" : "POST /api/admin (steward only)"}.
import { createApp } from "./_lib/core.mjs";
import { storeFromEnv } from "./_lib/stores.mjs";
import { CONFIG } from "./_lib/config.mjs";
let app = null;
const getApp = () => app ?? (app = (() => { const store = storeFromEnv(); return store && createApp({ store, ...CONFIG, adminSecret: process.env.SIGN_ADMIN_SECRET, log: (...a) => console.log(...a) }); })());
const unavailable = () => new Response("This signing page isn't set up yet (no storage is connected). Nothing was signed.", { status: 503, headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow" } });
async function handle(request) {
  const a = getApp(); if (!a) return unavailable();
  ${fn === "page" ? 'return a.page(request, new URL(request.url).searchParams.get("p") ?? "");' : "return a.admin(request);"}
}
export const GET = handle, POST = handle;
`;
const files = {
  "index.html": readFileSync(join(FRONT, "index.html"), "utf8"), "about.html": readFileSync(join(FRONT, "about.html"), "utf8"),
  "style.css": readFileSync(join(FRONT, "style.css"), "utf8"), "robots.txt": readFileSync(join(FRONT, "robots.txt"), "utf8"),
  "package.json": JSON.stringify({ name: "kigenka-sign", private: true, type: "module", engines: { node: "24.x" } }) + "\n",
  "vercel.json": JSON.stringify({ cleanUrls: true, rewrites: [{ source: "/p/:path(.*)", destination: "/api/p?p=:path" }], headers: front.headers }, null, 2) + "\n",
  "api/p.js": handler("page"), "api/admin.js": handler("admin"),
  "api/_lib/core.mjs": readFileSync(join(HERE, "src", "core.mjs"), "utf8"), "api/_lib/stores.mjs": readFileSync(join(HERE, "src", "stores.mjs"), "utf8"),
  "api/_lib/describe.mjs": readFileSync(join(REF, "describe.mjs"), "utf8"), "api/_lib/items.mjs": readFileSync(join(REF, "items.mjs"), "utf8"), "api/_lib/webauthn.mjs": readFileSync(join(REF, "webauthn.mjs"), "utf8"),
  "api/_lib/pages.mjs": `${LIC}// Generated by deploy/sign-serverless/build.mjs from reference/signing-page/public (unchanged).\nexport const PAGES = ${JSON.stringify(pages, null, 1)};\n`,
  "api/_lib/config.mjs": `${LIC}// Generated by deploy/sign-serverless/build.mjs: this deployment's fixed settings (not env vars, so they can't drift).\nexport const CONFIG = ${JSON.stringify(CONFIG)};\n`,
};
if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([f, t]) => !existsSync(join(OUT, f)) || readFileSync(join(OUT, f), "utf8") !== t).map(([f]) => f);
  if (stale.length) { console.log("sign-serverless: site/ is out of date: " + stale.join(", ") + " (run node deploy/sign-serverless/build.mjs)"); process.exit(1); }
  console.log("sign-serverless: site/ matches its sources ✓"); process.exit(0);
}
rmSync(OUT, { recursive: true, force: true });
for (const [f, t] of Object.entries(files)) { mkdirSync(dirname(join(OUT, f)), { recursive: true }); writeFileSync(join(OUT, f), t); }
console.log(`sign-serverless: wrote ${Object.keys(files).length} files to deploy/sign-serverless/site/`);
